/**
 * usePlaceholderStep.ts — 数字を 1 つ動かす (2026-09-20)
 *
 * オーナー指示:「デフォルトで収支の売値入れてくれてるじゃん。こういう灰色だけど計算に
 * 入ってるみたいな表記で数字動かすと 0 から始まるから、例えば 12.5 とかで灰色なら
 * 上は次 13、14、15 と 1 ずつ、下は 12、11、10 みたいな挙動して欲しいな」。
 * 追加 (実機で確認したオーナー):「灰色から 1 から始まるし、1 上げても小数点は変わらんし、
 * 変わるところと変わらんところある」。
 *
 * ## 規則 (灰色でも入力済みでも同じ)
 *   上 = floor(今の値) + 1 / 下 = ceil(今の値) − 1、下限 0。
 *   12.5 → 上 13・14・15 / 下 12・11・10。19.178 → 上 20・21 / 下 19・18。
 *   小数は 1 回動かした時点で整数に揃う (「1 上げても小数点が変わらない」を直した)。
 *   空欄なら灰色に出している値を今の値として使う (灰色は計算に入っているため)。
 *
 * ## なぜブラウザ任せにしないか
 * 最初は「矢印とスピナーは beforeinput を飛ばさない」で打ち込みと見分けていたが、
 * **アプリ (WebView2) では当てにならず**、オーナーの実機で直っていなかった。
 * 今は入力欄の既定のスピナーを消して、動かす口を 3 つとも自分で持つ:
 *   矢印キー / ホイール / 欄の右の ▲▼
 * 打ち込みは今まで通り素通しで、打った数がそのまま入る。
 */

/** 今の値 (空欄なら灰色の値) から 1 つ動かす */
export function stepFrom(current: number | null | undefined, placeholder: number | null | undefined, dir: 1 | -1): number {
  const base = current != null && Number.isFinite(current) ? current : placeholder;
  if (base == null || !Number.isFinite(base)) return dir > 0 ? 1 : 0;
  // 小数はまず整数に寄せる。12.5 → 上 13 / 下 12、19.178 → 上 20 / 下 19
  const next = dir > 0 ? Math.floor(base) + 1 : Math.ceil(base) - 1;
  return Math.max(0, next);
}
